<?php

declare(strict_types=1);

namespace Tests\Unit\Inventory\Domain\ObjectMother;

use Manager\Inventory\Domain\StockItem;
use Manager\Inventory\Domain\ValueObject\ProductId;
use Manager\Inventory\Domain\ValueObject\Quantity;
use Manager\Inventory\Domain\ValueObject\StockItemId;

final class StockItemMother
{
	public static function create(
		?StockItemId $id = null,
		?ProductId $productId = null,
		?Quantity $initialQuantity = null
	): StockItem {
		return StockItem::register(
			$id ?? StockItemIdMother::create(),
			$productId ?? ProductIdMother::create(),
			$initialQuantity ?? QuantityMother::create()
		);
	}

	/**
	 * Registers a stock item holding one active reservation.
	 *
	 * Every domain event generated by the setup is pulled, so the returned aggregate has no
	 * pending events and tests only ever observe the events raised by the operation being verified.
	 *
	 * @param positive-int|null $initialQuantity
	 * @param positive-int|null $reservationQuantity
	 */
	public static function withActiveReservation(
		?StockItemId $id = null,
		?ProductId $productId = null,
		?int $initialQuantity = null,
		?int $reservationQuantity = null
	): StockItem {
		$stockItem = self::create($id, $productId, QuantityMother::create($initialQuantity ?? 30));
		$stockItem->pullDomainEvents();

		$stockItem->reserve(
			ReservationIdMother::create(),
			OrderIdMother::create(),
			QuantityMother::create($reservationQuantity ?? 10)
		);
		$stockItem->pullDomainEvents();

		return $stockItem;
	}

	/**
	 * Registers a stock item whose single reservation has already been released, so the
	 * aggregate keeps the released reservation and an empty reserved counter.
	 *
	 * As with `withActiveReservation()`, every setup event is pulled: the returned
	 * aggregate starts with no pending events.
	 *
	 * @param positive-int|null $initialQuantity
	 * @param positive-int|null $reservationQuantity
	 */
	public static function withReleasedReservation(
		?StockItemId $id = null,
		?ProductId $productId = null,
		?int $initialQuantity = null,
		?int $reservationQuantity = null
	): StockItem {
		$stockItem = self::withActiveReservation($id, $productId, $initialQuantity, $reservationQuantity);

		$stockItem->releaseReservation($stockItem->reservations()[0]->id());
		$stockItem->pullDomainEvents();

		return $stockItem;
	}
}
